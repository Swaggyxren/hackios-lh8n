#!/usr/bin/env python3
"""
mkfont8x16.py: Rasterize printable ASCII into an 8x16 1-bit font emitted as a C header.
Runs on Linux or macOS via PIL / Pillow.
Usage: python3 mtk/tools/mkfont8x16.py > mtk/loader/font8x16.h
"""
import sys
from PIL import Image, ImageFont, ImageDraw

W, H = 8, 16
font_candidates = [
    "/usr/share/fonts/TTF/MesloLGLDZNerdFontMono-Bold.ttf",
    "/usr/share/fonts/TTF/JetBrainsMonoNerdFontMono-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf",
    "/System/Library/Fonts/Menlo.ttc",
]

font = None
for path in font_candidates:
    try:
        font = ImageFont.truetype(path, 13)
        break
    except Exception:
        continue

if font is None:
    font = ImageFont.load_default()

print("/* Generated by tools/mkfont8x16.py: ASCII 0x20-0x7e, 8x16, MSB = left. */")
print("static const unsigned char font8x16[95][16] = {")

for code in range(0x20, 0x7F):
    ch = chr(code)
    img = Image.new("L", (W, H), 0)
    draw = ImageDraw.Draw(img)
    draw.text((0, 0), ch, font=font, fill=255)
    
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)) > 100:
                b |= (0x80 >> x)
        rows.append(f"0x{b:02x}")
    label = ch if ch not in ("\\", "/*", "*/") else hex(code)
    print(f"    {{ {', '.join(rows)} }}, /* {label} */")

print("};")
