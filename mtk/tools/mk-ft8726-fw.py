#!/usr/bin/env python3
"""Generate hakios.ft8726_fw.h from the FT8726 firmware pulled from your own LH8n.

The touch driver (mtk/mt6833/drivers/input/hakios.mt6833_touch.c) #includes the generated
header. The firmware itself is vendor property and is never tracked: pull it from your phone
with `make firmware` (devices/lh8n/pull-firmware.sh), then run this script.

usage:
    mtk/tools/mk-ft8726-fw.py [FIRMWARE_BIN] [OUT_HEADER]

defaults:
    FIRMWARE_BIN = devices/lh8n/firmware/focaltech_ts_fw_00.bin
    OUT_HEADER   = mtk/mt6833/drivers/input/hakios.ft8726_fw.h

The file layout (PRAM 61112 bytes at 0x000000, DRAM 8904 bytes at 0xD00000) is the one the
FT8726 boot-ROM download expects; the header is just the first 70016 bytes of the vendor
firmware, 16 lowercase hex bytes per line.
"""
import os
import sys

PRAM_LEN = 61112
DRAM_LEN = 8904
TOTAL_LEN = PRAM_LEN + DRAM_LEN          # 70016
BYTES_PER_LINE = 16

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))   # mtk/tools/ is two below the tree top

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    ROOT, 'devices', 'lh8n', 'firmware', 'focaltech_ts_fw_00.bin')
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    ROOT, 'mtk', 'mt6833', 'drivers', 'input', 'hakios.ft8726_fw.h')

with open(src, 'rb') as f:
    data = f.read(TOTAL_LEN)

if len(data) < TOTAL_LEN:
    sys.exit('firmware %s is only %d bytes, need %d' % (src, len(data), TOTAL_LEN))

lines = [
    '/* Auto-generated by mtk/tools/mk-ft8726-fw.py from the firmware pulled from your own phone. */',
    '#define FT8726_FW_TOTAL_LEN %dU' % TOTAL_LEN,
    '#define FT8726_FW_PRAM_LEN  %dU' % PRAM_LEN,
    '#define FT8726_FW_DRAM_LEN  %dU' % DRAM_LEN,
    'static const uint8_t ft8726_fw_bin[] = {',
]
for i in range(0, TOTAL_LEN, BYTES_PER_LINE):
    chunk = data[i:i + BYTES_PER_LINE]
    lines.append('\t' + ' '.join('0x%02x,' % b for b in chunk))
lines.append('};')
lines.append('')

os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, 'w') as f:
    f.write('\n'.join(lines))

print('Generated %s (%d bytes of firmware) from %s' % (out, TOTAL_LEN, src))
